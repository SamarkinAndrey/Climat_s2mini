#pragma once
// FPCS-прореживание окна (Feature-Preserving Compressed Sampling).
//
// Из n сырых замеров одного пятиминутного окна выбирает 1..4 «важных» точки
// (для полного окна обычно 3..4):
//   * T   — одно значение на окно (среднее), оно проставляется всем выходным
//           строкам: температура медленная, пики для неё не нужны;
//   * H   — min и max, если разброс не меньше thH (иначе это шум DHT22);
//   * CO2 — min, max и «перегиб» (максимум второй разности), если разброс не
//           меньше thCo2.
// Границы окна (первый и последний замер) включаются всегда. Если окно
// ровное и признаков не нашлось, добавляется средний по времени замер, чтобы
// на сутки получалось не меньше 3 точек на окно (288 * 3 = 864).
// Дубликаты склеиваются по индексу замера, поэтому одна строка — один полный
// снимок {ts, t, h, co2}, даже если в этот момент совпали сразу несколько
// экстремумов. T/H = NaN означает «замера не было»: NaN не участвует в
// среднем T и в поиске экстремумов H. Если валидной T нет вовсе, наружу
// уходит NaN.
//
// Жёсткий лимит 4 точки на окно выбран под суточный бюджет: 288 * 4 = 1152
// точки, что укладывается в кольцо liveBuf на 1200 и в лимит «до 1200 в сутки».
// CO2 важнее H, поэтому max CO2 добавляется раньше H-экстремумов и не теряется
// при нехватке места.
//
// Модуль намеренно не зависит от Arduino: только stdint.h/stddef.h/math.h,
// без динамической памяти, String и std::vector.

#include <stddef.h>
#include <stdint.h>

struct Sample {
  uint32_t ts;   // Unix-время замера, с (0 — время ещё не синхронизировано)
  float    t;    // температура, °C
  float    h;    // влажность, %
  uint16_t co2;  // CO2, ppm (0 — валидного замера не было)
};

struct FpcsConfig {
  float    thH   = 5.0f; // %: разброс меньше — шум DHT22 (±1–2 %)
  uint16_t thCo2 = 50;   // ppm: разброс меньше — шум MH-Z19 (±10–20 ppm)
};

// Жёсткий предел выходных точек на окно. 288 окон * 4 = 1152 точки в сутки:
// это и суточный бюджет, и гарантия, что кольцо liveBuf (1200) покрывает 24 ч.
static const size_t FPCS_MAX_OUT = 4;

// Возвращает число точек (1..FPCS_MAX_OUT), записанных в out.
// out должен вмещать FPCS_MAX_OUT элементов.
size_t fpcs_select(const Sample *in, size_t n, Sample *out, const FpcsConfig &cfg);
